// Concatenates the ES modules in js/ into one classic script (js/bundle.js) so that index.html
// also works when opened directly from disk (file://), where browsers block module scripts.
import fs from 'fs';
const order = ['horizon', 'sun', 'fmt', 'data', 'terrain', 'map', 'panorama', 'carpet', 'app'];
let out = '// Generated by _build/bundle.mjs – edit the files in js/ instead.\n(() => {\n\'use strict\';\n';
for (const f of order) {
  const src = fs.readFileSync(`../js/${f}.js`, 'utf8')
    .replace(/^import .*?;\s*$/gm, '')
    .replace(/^export (async function|function|class|const|let)/gm, '$1');
  out += `\n// ---- ${f}.js ----\n${src}`;
}
fs.writeFileSync('../js/bundle.js', out + '\n})();\n');
console.log('bundle', (out.length / 1024).toFixed(0), 'kB');
